"""Build reviewer_a2_order.py: the reviewer's EXP A2 (exp_devils_advocate.py lines 196-350) copied VERBATIM,
re-indented into a function run(AT_LAST), with ONE switch: AT_LAST=True moves the unary `at` loop after the
binary-operator loops inside each layer (the order the tg-probe prototype uses: + - * mod max min at ...).
Usage: python3 make_reviewer_a2_order.py && python3 reviewer_a2_order.py"""
import re

SRC = '/home/tlh24/lisploop/plan_v2c_audit/round3/reviewer/exp_devils_advocate.py'
lines = open(SRC).read().split('\n')[195:350]           # lines 196..350
body = '\n'.join(lines)

AT_OLD = (
"                # Unary 'at xs idx' (cost +1 op)\n"
"                for t1, c1, _ in by[s - 1]:\n"
"                    cands_eval += 1\n"
"                    out = eval_at(c1)\n"
"                    if out is None: continue\n"
"                    if out == r_tgt: return ('at', 'xs', t1), cands_eval, cands_skip, len(seen)\n"
"                    if not is_final and out not in seen:\n"
"                        seen.add(out); by[s].append((('at', 'xs', t1), out, mk_abs(out)))")
AT_NEW = (
"                def at_block():\n"
"                    nonlocal cands_eval\n"
"                    for t1, c1, _ in by[s - 1]:\n"
"                        cands_eval += 1\n"
"                        out = eval_at(c1)\n"
"                        if out is None: continue\n"
"                        if out == r_tgt: return ('at', 'xs', t1)\n"
"                        if not is_final and out not in seen:\n"
"                            seen.add(out); by[s].append((('at', 'xs', t1), out, mk_abs(out)))\n"
"                    return None\n"
"                if not AT_LAST:\n"
"                    hit = at_block()\n"
"                    if hit: return hit, cands_eval, cands_skip, len(seen)")
